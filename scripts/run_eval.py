"""Run the deterministic evaluation, print the report, and save it to docs/eval_results.md.

Usage: python scripts/run_eval.py
"""
from datetime import date

from eob.evaluation import ROOT, evaluate_all, format_report


def main() -> None:
    results, summary = evaluate_all()
    report = format_report(summary, results)
    print(report)
    stamped = f"<!-- generated by scripts/run_eval.py on {date.today().isoformat()} -->\n{report}"
    (ROOT / "docs" / "eval_results.md").write_text(stamped, encoding="utf-8")
    print("Saved to docs/eval_results.md")


if __name__ == "__main__":
    main()
