"""Score the deterministic rules engine on the held-out set and save docs/eval_heldout_engine.md.

No AI and no cost. Usage: python scripts/run_eval_heldout.py
"""
from datetime import date

from eob.evaluation import ROOT, evaluate_all, format_report

GOLD = ROOT / "fixtures" / "heldout" / "gold.json"
OUT = ROOT / "docs" / "eval_heldout_engine.md"


def main() -> None:
    results, summary = evaluate_all(GOLD)
    report = format_report(summary, results)
    report = report.replace("# Evaluation results: deterministic rules engine", "# Held-out evaluation: deterministic rules engine", 1)
    report = report.replace("(HL7 CARIN examples plus synthetic scenarios)", "(held-out synthetic scenarios)")
    print(report)
    OUT.write_text(f"<!-- generated by scripts/run_eval_heldout.py on {date.today().isoformat()} -->\n{report}", encoding="utf-8")
    print(f"Saved to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()